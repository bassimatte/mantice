def run(
    preset_paths: List[Path],
    cli_seed: Optional[int],
    cli_duration: Optional[float],
    audio_format: str,
    solo_layer: Optional[str] = None,
    auto_template: Optional[str] = None,
    no_automation: bool = False,
) -> None:
    ok = failed = 0
    total = len(preset_paths)

    for idx, preset_path in enumerate(preset_paths, 1):
        try:
            with warnings.catch_warnings(record=True) as caught:
                warnings.simplefilter("always")
                preset = load_preset(preset_path)
                for w in caught:
                    print(f"  ⚠  {w.message}")

            # Override duration from CLI if specified
            if cli_duration is not None:
                preset["duration"] = cli_duration

            # Apply / strip automation
            if no_automation:
                strip_automation(preset)
                print("  ⚙  Automation: disabled")
            elif auto_template:
                apply_auto_template(preset, auto_template)
                print(f"  ⚙  Automation template: {auto_template}")

            apply_seed(preset, cli_seed)

            name = preset["meta"].get("name", preset_path.stem)
            slug = preset["meta"].get("slug", preset_path.stem.lower().replace(" ", "_"))

            # ── Solo layer: disable all except the target ─────────────────
            solo_layer_name = None
            if solo_layer is not None:
                layers = preset["layers"]
                target_idx = None
                # Try as index first
                try:
                    idx_val = int(solo_layer)
                    if 0 <= idx_val < len(layers):
                        target_idx = idx_val
                except ValueError:
                    pass
                # Try as name match
                if target_idx is None:
                    query = solo_layer.lower()
                    for i, l in enumerate(layers):
                        if query in l.get("name", "").lower():
                            target_idx = i
                            break
                if target_idx is None:
                    print(f"  ✗ Layer '{solo_layer}' not found. Available layers:")
                    for i, l in enumerate(layers):
                        print(f"      {i}: {l.get('name', 'Layer ' + str(i))}")
                    failed += 1
                    continue
                # Disable all except target
                for i, l in enumerate(layers):
                    l["enabled"] = (i == target_idx)
                solo_layer_name = layers[target_idx].get("name", f"Layer {target_idx}")
                print(f"\n[{idx}/{total}] Generating: {name} — solo: {solo_layer_name}")
            else:
                print(f"\n[{idx}/{total}] Generating: {name}")

            # Build using StreamingDroneEngine (identical signal chain to web preview)
            seed = int(cli_seed) if cli_seed is not None else (preset.get("seed") or 42)
            engine = StreamingDroneEngine(preset, seed=seed)

            sr           = _engine_config.SAMPLE_RATE
            total_samp   = int(preset["duration"] * sr)
            chunk_size   = 2048
            n_chunks     = (total_samp + chunk_size - 1) // chunk_size
            progress     = ProgressBar(n_chunks, description="Rendering")
            chunks, rem  = [], total_samp
            while rem > 0:
                n = min(chunk_size, rem)
                chunks.append(engine.next_chunk(n))
                rem -= n
                progress.update(1)
            progress.finish()
            audio = np.concatenate(chunks, axis=0)

            # Export audio — append layer name if solo
            if solo_layer_name:
                safe_name = "".join(c for c in name if c.isalnum() or c in " -_").strip()
                safe_layer = "".join(c for c in solo_layer_name if c.isalnum() or c in " -_").strip()
                audio_filename = f"{safe_name} - Solo {safe_layer}.{audio_format}"
            else:
                audio_filename = f"{slug}.{audio_format}"
            out_path = EXPORT_DIR / audio_filename
            export_audio(out_path, audio, fmt=audio_format)
            print(f"  ✓ Saved: {out_path}")

            # Generate Freesound bulk upload XLS
            xlsx_path = EXPORT_DIR / f"{slug}.xlsx"
            write_freesound_xlsx(xlsx_path, audio_filename, preset)
            if HAS_OPENPYXL:
                print(f"  ✓ Freesound metadata: {xlsx_path}")

            ok += 1

        except Exception as exc:
            print(f"  ✗ Failed ({preset_path.name}): {exc}", file=sys.stderr)
            failed += 1

    print(f"\n{'─' * 40}")
    print(f"Done — {ok} exported, {failed} failed.")


def list_presets(preset_paths: List[Path]) -> None:
    """Print available presets in a readable table."""
    print(f"{'#':<4} {'Name':<30} {'Source':<12} {'Category':<14} {'Duration':<8} Path")
    print("─" * 110)
    for i, p in enumerate(preset_paths, 1):
        try:
            with warnings.catch_warnings(record=True):
                warnings.simplefilter("always")
                preset = load_preset(p)
            meta = preset.get("meta", {})
            name = meta.get("name", p.stem)
            cat  = meta.get("category", "—")
            dur  = f"{preset['duration']:.0f}s"
            # Check if community preset
            source = "Community" if p.parts[0] == "shared" else "Official"
            # Add author for community presets
            if source == "Community":
                author = meta.get("author", "")
                if author:
                    name = f"{name} (by {author})"
        except Exception:
            name, cat, dur = p.stem, "?", "?"
            source = "Community" if p.parts[0] == "shared" else "Official"
        print(f"{i:<4} {name:<30} {source:<12} {cat:<14} {dur:<8} {p}")
    
    # Summary
    official_count = sum(1 for p in preset_paths if p.parts[0] != "shared")
    community_count = sum(1 for p in preset_paths if p.parts[0] == "shared")
    print(f"\n{len(preset_paths)} preset(s) found: {official_count} official, {community_count} community.")


def find_preset_by_name(preset_paths: List[Path], name: str) -> List[Path]:
    """Find presets whose name or filename matches the query (case-insensitive)."""
    query = name.lower()
    matches = []
    for p in preset_paths:
        # Match against filename stem
        if query in p.stem.lower():
            matches.append(p)
            continue
        # Match against meta.name inside the file
        try:
            with warnings.catch_warnings(record=True):
                warnings.simplefilter("always")
                preset = load_preset(p)
            meta_name = preset.get("meta", {}).get("name", "")
            if query in meta_name.lower():
                matches.append(p)
        except Exception:
            pass
    return matches


