def write_freesound_xlsx(xlsx_path: Path, audio_filename: str, preset: dict) -> None:
    """Generate Freesound bulk upload XLS file with proper metadata."""
    if not HAS_OPENPYXL:
        print("  ⚠️  openpyxl not installed, skipping XLS generation. Install with: pip install openpyxl", file=sys.stderr)
        return
    
    meta = preset.get("meta", {})
    
    # Create workbook
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Freesound Upload"
    
    # Headers (Freesound bulk upload format)
    headers = ["audio_filename", "name", "tags", "geotag", "description", "license", "pack_name", "is_explicit"]
    ws.append(headers)
    
    # Build metadata row
    row = [
        audio_filename,
        meta.get("name", Path(audio_filename).stem),
        build_tags(preset),
        "",  # geotag (empty)
        build_freesound_description(preset),
        "Creative Commons 0",
        "MANTICE Drones",
        "0"  # not explicit
    ]
    ws.append(row)
    
    # Auto-adjust column widths
    for col in ws.columns:
        max_length = 0
        col_letter = col[0].column_letter
        for cell in col:
            if cell.value:
                max_length = max(max_length, len(str(cell.value)))
        adjusted_width = min(max_length + 2, 100)  # Cap at 100 for description
        ws.column_dimensions[col_letter].width = adjusted_width
    
    # Save
    wb.save(xlsx_path)


